"""Sort a fine-tuned model's mistakes on silver val, field by field.

Input: predictions_val_<run>.json from the notebook (page spans per listing, at o_scale 1.0).
Silver val is the reference, so a "false positive" here can be a real model mistake or a real
span that silver missed. This script cannot tell those two apart, so it sorts each false
positive by what it looks like, and writes samples with context to read by hand.

False positive kinds (predicted span with no exactly matching silver span of the same label):
  boundary         overlaps a silver span of the same label, but start or end differs
  wrong label      overlaps a silver span of a different label (label confusion)
  repeat           no overlap, but the same text (or, for deadline and fee, the same parsed value)
                   is a silver span of this label elsewhere on the page: a restated mention
                   that silver did not label
  other            no overlap and nothing like it in silver: a silver miss or a real mistake
False negatives: silver spans with no overlapping prediction, with the silver sources.

  python models/extraction/model_error_analysis.py roberta_neg3
  python models/extraction/model_error_analysis.py roberta_neg3 --n 12 --seed 1
"""
import argparse
import json
import random
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import evaluate as ev  # noqa: E402

LABELED = ROOT / "data" / "labeled"
RESULTS = ROOT / "docs" / "results"
PAD = 90


def overlaps(a, b):
    return a[0] < b[1] and b[0] < a[1]


def context(text, s, e):
    left = text[max(0, s - PAD):s].replace("\n", " ")
    right = text[e:e + PAD].replace("\n", " ")
    return f"{left}[[{text[s:e]}]]{right}"


def norm(t):
    return " ".join(t.lower().split())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run", help="e.g. roberta_neg3 (reads data/labeled/predictions_val_<run>.json)")
    ap.add_argument("--n", type=int, default=10, help="examples per field and kind")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    pred = {k: [tuple(x) for x in v] for k, v in json.loads(
        (LABELED / f"predictions_val_{args.run}.json").read_text(encoding="utf-8")).items()}
    ev_val = json.loads((LABELED / "eval_val.json").read_text(encoding="utf-8"))
    texts = {lid: v["text"] for lid, v in ev_val.items()}
    silver = {}
    with open(LABELED / "silver.jsonl", encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if r["split"] == "val":
                silver[r["listing_id"]] = r["spans"]

    kinds = ["boundary", "wrong label", "repeat", "other"]
    fp = {f: {k: [] for k in kinds} for f in ev.FIELDS}
    fn = {f: [] for f in ev.FIELDS}
    exact_ok = Counter()
    totals = {f: [0, 0] for f in ev.FIELDS}  # silver, predicted
    for lid, g_all in silver.items():
        text = texts[lid]
        p_all = pred.get(lid, [])
        for f in ev.FIELDS:
            g = [(s["start"], s["end"], "+".join(s["sources"])) for s in g_all if s["label"] == f]
            p = [(s, e) for (l, s, e) in p_all if l == f]
            totals[f][0] += len(g)
            totals[f][1] += len(p)
            g_text = {norm(text[a:b]) for a, b, _ in g}
            g_val = {ev.parse_value(f, text[a:b]) for a, b, _ in g} - {None} if f in ("deadline", "fee") else set()
            for ps in p:
                if any((a, b) == ps for a, b, _ in g):
                    exact_ok[f] += 1
                    continue
                if any(overlaps(ps, (a, b)) for a, b, _ in g):
                    fp[f]["boundary"].append((lid, ps, ""))
                elif any(l != f and overlaps(ps, (s, e)) for (l, s, e) in
                         [(x["label"], x["start"], x["end"]) for x in g_all]):
                    other_l = [x["label"] for x in g_all if x["label"] != f and overlaps(ps, (x["start"], x["end"]))]
                    fp[f]["wrong label"].append((lid, ps, "silver says " + "/".join(other_l)))
                elif norm(text[ps[0]:ps[1]]) in g_text or (g_val and ev.parse_value(f, text[ps[0]:ps[1]]) in g_val):
                    fp[f]["repeat"].append((lid, ps, ""))
                else:
                    fp[f]["other"].append((lid, ps, ""))
            for a, b, src in g:
                if not any(overlaps((a, b), ps) for ps in p):
                    fn[f].append((lid, (a, b), src))

    rng = random.Random(args.seed)
    lines = [f"# Errors of `{args.run}` on silver val (o_scale 1.0)", "",
             "Generated by `models/extraction/model_error_analysis.py`. A false positive is a predicted span with "
             "no exactly matching silver span of the same label. Silver is not perfect, so a false positive can be a "
             "real span silver missed; `repeat` and `other` are the kinds to read by hand.", "",
             "| Field | Silver | Predicted | Exact hits | FP boundary | FP wrong label | FP repeat | FP other | Missed (FN) |",
             "|---|---|---|---|---|---|---|---|---|"]
    for f in ev.FIELDS:
        c = [len(fp[f][k]) for k in kinds]
        lines.append(f"| {f} | {totals[f][0]} | {totals[f][1]} | {exact_ok[f]} | {c[0]} | {c[1]} | {c[2]} | {c[3]} | {len(fn[f])} |")
    lines.append("")
    for f in ev.FIELDS:
        lines += [f"## {f}", ""]
        for k in kinds:
            items = fp[f][k]
            lines += [f"### False positives: {k} ({len(items)})", ""]
            for lid, (s, e), note in sorted(rng.sample(items, min(args.n, len(items)))):
                lines.append(f"- `{lid}` {note} {context(texts[lid], s, e)}")
            if not items:
                lines.append("- none")
            lines.append("")
        circ = Counter("LLM found it" if "llm" in src.split("+") else "rule-only sources" for _, _, src in fn[f])
        lines += [f"### Missed silver spans ({len(fn[f])}; {dict(circ)})", ""]
        for lid, (s, e), src in sorted(rng.sample(fn[f], min(args.n, len(fn[f])))):
            lines.append(f"- `{lid}` `{src}` {context(texts[lid], s, e)}")
        if not fn[f]:
            lines.append("- none")
        lines.append("")

    out = RESULTS / f"model_errors_{args.run}.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:12]).encode("ascii", "replace").decode())
    print(f"\nwritten: {out}")


if __name__ == "__main__":
    main()
