"""List the regex baseline's mistakes on silver, field by field, so rules can be improved.

For one silver split (train by default) it finds
  false positives   the baseline predicted a span and silver has no span of the same
                    label that overlaps it
  false negatives   silver has a span and the baseline has no overlapping span
  boundary errors   the two overlap but the start or end differs (counted only)
and writes a sample of each, with context, to docs/results/regex_errors_<split>.md.

Each false negative shows which silver sources found it. A span found only by the
silver regex or by distant supervision ("rule-only sources") is circular evidence:
the baseline missing it says little. Spans the LLM found are better evidence.

Use train to improve the rules. Check on val. Never use gold for this.

  python models/extraction/error_analysis.py                  # train, 15 per kind
  python models/extraction/error_analysis.py --split val --n 10
"""
import argparse
import json
import random
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import evaluate as ev  # noqa: E402
from regex_baseline import extract, load_texts  # noqa: E402

LABELED = ROOT / "data" / "labeled"
RESULTS = ROOT / "docs" / "results"
PAD = 80


def load_silver_full(split):
    """{listing_id: [{label, start, end, sources}]}"""
    out = {}
    with open(LABELED / "silver.jsonl", encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if r["split"] == split:
                out[r["listing_id"]] = r["spans"]
    return out


def overlaps(a, b):
    return a[0] < b[1] and b[0] < a[1]


def context(text, s, e):
    left = text[max(0, s - PAD):s].replace("\n", " ")
    right = text[e:e + PAD].replace("\n", " ")
    return f"{left}[[{text[s:e]}]]{right}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="train", choices=["train", "val"])
    ap.add_argument("--n", type=int, default=15, help="examples per field and kind")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    if args.split == "val":
        print("NOTE: val is the check set. Do not tune rules on its errors.\n")

    silver = load_silver_full(args.split)
    texts = load_texts(silver)
    pred = {lid: extract(texts[lid]) for lid in silver}

    fp, fn, boundary, totals = {}, {}, Counter(), {}
    for f in ev.FIELDS:
        fp[f], fn[f] = [], []
        totals[f] = {"silver": 0, "pred": 0}
    for lid, spans in silver.items():
        for f in ev.FIELDS:
            g = [(s["start"], s["end"], s["sources"]) for s in spans if s["label"] == f]
            p = [(s, e) for (l, s, e) in pred[lid] if l == f]
            totals[f]["silver"] += len(g)
            totals[f]["pred"] += len(p)
            for ps in p:
                hits = [x for x in g if overlaps(ps, x)]
                if not hits:
                    fp[f].append((lid, ps[0], ps[1], ""))
                elif not any((x[0], x[1]) == ps for x in hits):
                    boundary[f] += 1
            for gs in g:
                if not any(overlaps(gs, ps) for ps in p):
                    fn[f].append((lid, gs[0], gs[1], "+".join(gs[2])))

    rng = random.Random(args.seed)
    lines = [f"# Regex baseline errors on silver {args.split}", "",
             "Generated by `models/extraction/error_analysis.py`. Overlap matching: a predicted span is a "
             "false positive if no silver span of the same label overlaps it.", "",
             "| Field | Silver spans | Predicted | False positives | False negatives | Boundary errors |",
             "|---|---|---|---|---|---|"]
    for f in ev.FIELDS:
        lines.append(f"| {f} | {totals[f]['silver']} | {totals[f]['pred']} | {len(fp[f])} | "
                     f"{len(fn[f])} | {boundary[f]} |")
    lines.append("")
    for f in ev.FIELDS:
        circ = Counter()
        for _, _, _, src in fn[f]:
            circ["rule-only sources" if "llm" not in src.split("+") else "LLM found it"] += 1
        lines += [f"## {f}", "",
                  f"False negatives by evidence: {dict(circ)}", ""]
        for title, items in (("False positives (predicted, not in silver)", fp[f]),
                             ("False negatives (in silver, missed)", fn[f])):
            lines += [f"### {title}", ""]
            pick = rng.sample(items, min(args.n, len(items)))
            for lid, s, e, src in sorted(pick):
                tag = f" `{src}`" if src else ""
                lines.append(f"- `{lid}`{tag} {context(texts[lid], s, e)}")
            if not pick:
                lines.append("- none")
            lines.append("")

    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / f"regex_errors_silver_{args.split}.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:12]).encode("ascii", "replace").decode())
    print(f"\nwritten: {out}")


if __name__ == "__main__":
    main()
